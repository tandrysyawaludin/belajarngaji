export interface IqraJilid {
  id: number;
  title: string;
  href: string;
  available: boolean;
}

export type IqraCell = string | readonly string[];

export interface IqraNoteRow {
  kind: "note";
  text: string;
  tone?: "normal" | "warning";
}

export interface IqraSplitNoteRow {
  kind: "split-note";
  left: readonly IqraCell[];
  text: string;
  right: readonly IqraCell[];
}

export interface IqraTeachingRow {
  kind: "teaching";
  text: string;
  marks: readonly IqraCell[];
  target?: string;
}

export interface IqraWaqfTableRow {
  kind: "waqf-table";
  entries: readonly {
    sign: string;
    text: string;
  }[];
}

export type IqraRow =
  | readonly IqraCell[]
  | IqraNoteRow
  | IqraSplitNoteRow
  | IqraTeachingRow
  | IqraWaqfTableRow;

export interface IqraPage {
  jilid: number;
  page: number;
  title: string;
  subtitle: string;
  showBismillah?: boolean;
  footerNote?: string;
  rows: readonly IqraRow[];
}

